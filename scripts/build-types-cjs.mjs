// Generates types/index.d.cts, the declaration for `require('swell-js')`,
// node10 module resolution and the browser global. `export =` cannot be
// combined with named exports, so every named type of the ESM declaration is
// mirrored in a namespace. Run `npm run build:types` after changing types;
// `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'types/index.d.ts');
const target = join(root, 'types/index.d.cts');
const esm = "import('./index.js', { with: { 'resolution-mode': 'import' } })";

const program = ts.createProgram([source], {
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  skipLibCheck: true,
});
const checker = program.getTypeChecker();
const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(source));

const lines = [
  '// Generated by scripts/build-types-cjs.mjs from types/index.d.ts. Do not edit.',
  "import type { SwellClientDefault } from './index.js' with { 'resolution-mode': 'import' };",
  '',
  "declare const swell: SwellClientDefault<'snake'>;",
  '',
  'declare namespace swell {',
];

for (const symbol of checker.getExportsOfModule(moduleSymbol)) {
  if (symbol.name === 'default') continue;
  const resolved =
    symbol.flags & ts.SymbolFlags.Alias
      ? checker.getAliasedSymbol(symbol)
      : symbol;
  if (!(resolved.flags & ts.SymbolFlags.Type)) {
    throw new Error(`${symbol.name} is not a type; extend the generator`);
  }
  const declaration = resolved.declarations[0];
  const params = declaration.typeParameters ?? [];
  const list = (map) =>
    params.length ? `<${params.map(map).join(', ')}>` : '';
  const declared = list((p) => p.getText(declaration.getSourceFile()));
  const applied = list((p) => p.name.text);
  lines.push(
    `  export type ${symbol.name}${declared} = ${esm}.${symbol.name}${applied};`,
  );
}

lines.push('}', '', 'export as namespace swell;', 'export = swell;', '');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('types/index.d.cts is stale: run `npm run build:types`');
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
